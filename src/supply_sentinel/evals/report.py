"""Reports and CI gates (spec 05 sections 7 and 8). Every number comes from a results file."""

import json
from pathlib import Path
from typing import Any

from supply_sentinel.evals.scenario import SUITES

CATEGORIES = ("shortage", "ltb", "eo", "negative", "robustness")
GROUND_MIN = 0.95
Doc = dict[str, Any]


def load_results(results_dir: Path) -> list[tuple[Path, Doc]]:
    out = []
    for f in sorted(results_dir.glob("2*.json")):  # timestamped raw files only
        out.append((f, json.loads(f.read_text(encoding="utf-8"))))
    return out


def _rate(rows: list[Doc], scorer: str) -> float | None:
    vals = [r["scores"][scorer]["passed"] for r in rows if scorer in r["scores"]]
    vals = [v for v in vals if v is not None]
    return None if not vals else sum(bool(v) for v in vals) / len(vals)


def grounding_ratio(rows: list[Doc]) -> float | None:
    num = sum(r["scores"].get("grounding", {}).get("num", 0) for r in rows)
    den = sum(r["scores"].get("grounding", {}).get("den", 0) for r in rows)
    return None if den == 0 else num / den


def pass_hat_k(rows: list[Doc], k: int) -> float | None:
    """Share of scenarios that passed in all of their runs, when every scenario has >= k runs."""
    by: dict[str, list[bool]] = {}
    for r in rows:
        by.setdefault(r["scenario_id"], []).append(bool(r["passed"]))
    if not by or any(len(v) < k for v in by.values()):
        return None
    return sum(all(v) for v in by.values()) / len(by)


def summarize(doc: Doc) -> Doc:
    rows: list[Doc] = doc["results"]
    n = len(rows)
    usage = [r["usage"] for r in rows]
    return {
        "runs": n,
        "pass_rate": sum(r["passed"] for r in rows) / n if n else None,
        "action": _rate(rows, "action"),
        "quantity": _rate(rows, "quantity"),
        "grounding": grounding_ratio(rows),
        "safety": _rate(rows, "safety"),
        "comms": _rate(rows, "comms"),
        "pass3": pass_hat_k(rows, 3),
        "tokens_per_scenario": (
            sum(u["input_tokens"] + u["output_tokens"] for u in usage) / n if n else None
        ),
        "cost_usd": sum(u["cost_usd"] for u in usage),
        "crashed": sum(bool(r["crashed"]) for r in rows),
    }


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{x:.0%}"


def _model(doc: Doc) -> str:
    m = doc["meta"]
    return m["system"] if m["system"] == "rules" else f"{m['profile']}"


def leaderboard(docs: list[tuple[Path, Doc]]) -> str:
    latest: dict[tuple[str, str, str], tuple[Path, Doc]] = {}
    for path, doc in docs:
        m = doc["meta"]
        latest[(m["suite"], m["system"], m["profile"])] = (path, doc)  # sorted by time: last wins
    lines = [
        "# Leaderboard",
        "",
        "Generated by `sentinel eval report` from files in `evals/results/`.",
        "",
    ]
    for suite in SUITES:
        group = [(k, v) for k, v in latest.items() if k[0] == suite]
        if not group:
            continue
        lines += [
            f"## Suite `{suite}`",
            "",
            "| System | Profile / model | Scenarios | Pass rate | Action acc | Qty acc | "
            "Grounding | "
            "Safety | Comms >=4 | pass^3 | Tokens/scenario | Cost | Results file |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for (_, system, _), (path, doc) in sorted(group, key=lambda g: g[0][1:]):
            s = summarize(doc)
            tok = "-" if s["tokens_per_scenario"] is None else f"{s['tokens_per_scenario']:,.0f}"
            lines.append(
                f"| {system} | {_model(doc)} | {s['runs']} | {_pct(s['pass_rate'])} | "
                f"{_pct(s['action'])} | {_pct(s['quantity'])} | {_pct(s['grounding'])} | "
                f"{_pct(s['safety'])} | {_pct(s['comms'])} | {_pct(s['pass3'])} | {tok} | "
                f"${s['cost_usd']:.2f} | `{path.name}` |"
            )
        lines.append("")
        lines += _category_table(group)
    lines += _failures(list(latest.values()))
    return "\n".join(lines).rstrip() + "\n"


def _category_table(group: list[tuple[Any, tuple[Path, Doc]]]) -> list[str]:
    head = "| System | " + " | ".join(CATEGORIES) + " |"
    lines = ["### Pass rate by category", "", head, "|---|" + "---|" * len(CATEGORIES)]
    for (_, system, profile), (_, doc) in sorted(group, key=lambda g: g[0][1:]):
        cells = []
        for cat in CATEGORIES:
            rows = [r for r in doc["results"] if r["category"] == cat]
            cells.append("-" if not rows else f"{sum(r['passed'] for r in rows)}/{len(rows)}")
        label = system if system == "rules" else f"{system} ({profile})"
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return [*lines, ""]


def _failures(entries: list[tuple[Path, Doc]]) -> list[str]:
    lines = ["## Failures", ""]
    any_fail = False
    for _, doc in entries:
        m = doc["meta"]
        for r in doc["results"]:
            if r["passed"]:
                continue
            any_fail = True
            bad = [
                f"{n}: {s['detail']}"
                for n, s in r["scores"].items()
                if s["hard"] and s["passed"] is False
            ]
            link = f" - ledger `{r['ledger']}`" if r.get("ledger") else ""
            why = r["error"] or "; ".join(bad)
            lines.append(f"- `{m['suite']}/{m['system']}/{m['profile']}` **{r['scenario_id']}** "
                         f"run {r['run_idx']}: {why}{link}")  # fmt: skip
    if not any_fail:
        lines.append("None.")
    return [*lines, ""]


def run_markdown(path: Path, doc: Doc) -> str:
    """Human-readable companion to one raw results file."""
    m, s = doc["meta"], summarize(doc)
    lines = [
        f"# {m['suite']} / {m['system']} / {m['profile']}",
        "",
        f"Started {m['started']}. k={m['k']}. Pass rate {_pct(s['pass_rate'])} "
        f"({sum(r['passed'] for r in doc['results'])}/{s['runs']}). Raw data: `{path.name}`.",
        "",
        "| Scenario | Run | Result | Primary | Qty | Tier | Failed hard scorers |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in doc["results"]:
        rec = r["rec"] or {}
        prim = rec.get("primary") or {}
        failed = ", ".join(n for n, x in r["scores"].items() if x["hard"] and x["passed"] is False)
        verdict = "PASS" if r["passed"] else "FAIL"
        lines.append(
            f"| {r['scenario_id']} | {r['run_idx']} | {verdict} | {prim.get('action_type', '-')} | "
            f"{prim.get('quantity', '-')} | {rec.get('tier', '-')} | {failed or '-'} |"
        )
    return "\n".join(lines) + "\n"


