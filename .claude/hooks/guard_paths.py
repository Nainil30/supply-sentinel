#!/usr/bin/env python3
"""PreToolUse hook: block coding-agent edits to protected paths.

Reads the hook payload (JSON) from stdin. Exit code 2 blocks the tool call and
sends stderr back to Claude as the reason. Any unexpected error fails open
(exit 0) so a broken hook never bricks a session.

Protected:
  - .env and .env.<anything> except .env.example      (secrets)
  - data/snapshots/**                                   (generated, read-only data)
  - evals/results/baseline_*.json                       (locked baselines; owner copies them)
  - evals/human_labels/** that already exist            (agent may create a template, never edit labels)

This is a guardrail, not a sandbox: shell commands could still write files.
The deny rules in settings.json and code review cover the rest.
"""

from __future__ import annotations

import fnmatch
import json
import os
import sys
from pathlib import Path


def _block(reason: str) -> None:
    print(f"Blocked by guard_paths hook: {reason}", file=sys.stderr)
    sys.exit(2)


def main() -> None:
    try:
        payload = json.load(sys.stdin)
    except Exception:
        sys.exit(0)

    tool_input = payload.get("tool_input") or {}
    raw_path = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not raw_path:
        sys.exit(0)

    project_dir = Path(os.environ.get("CLAUDE_PROJECT_DIR", payload.get("cwd", "."))).resolve()
    target = Path(raw_path)
    if not target.is_absolute():
        target = (project_dir / target).resolve()
    else:
        target = target.resolve()

    try:
        rel = target.relative_to(project_dir).as_posix()
    except ValueError:
        sys.exit(0)  # outside the repo: not our concern

    name = target.name
    if name == ".env" or (name.startswith(".env.") and name != ".env.example"):
        _block("secrets files are edited by the owner only. Use .env.example for documentation.")

    if fnmatch.fnmatch(rel, "data/snapshots/*"):
        _block(
            "snapshots are generated by `sentinel datagen` / `sentinel scenario build`, never edited by hand."
        )

    if fnmatch.fnmatch(rel, "evals/results/baseline_*.json"):
        _block(
            "locked eval baselines are copied by the owner. Write new results to a new file instead."
        )

    if fnmatch.fnmatch(rel, "evals/human_labels/*") and target.exists():
        _block(
            "human labels are ground truth written by the owner. You may create a new template, not edit labels."
        )

    sys.exit(0)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:
        sys.exit(0)
